// Odessa Prime Slots — Phase 4.3 asset bake pipeline.
//
// Renders each of the 6 SLOT_CATALOG cabinets (and the hall background) from
// the HTML/CSS templates in cabinetTemplate.mjs into flat, transparent PNGs
// under public/assets/casino/slots/. This runs ONCE, offline, via a headless
// Chromium instance — the app never re-renders this markup at runtime, it
// only displays the resulting <img>.
//
// These are TEMPORARY placeholder cabinet assets (see docs/SPRINT_ODESSA_PRIME_SLOTS_ROOM_4_3_RESULT.md,
// "FINAL_ASSET_STATUS = TEMPORARY"). They are not photoreal. Swapping them
// for real photoreal/3D-rendered cutouts later requires no code change:
// just replace the PNG files at the same paths and re-run this script's
// geometry step (or hand-measure the new screen rect) if the layout moves.
//
// Usage: node scripts/casino-slots/generate-cabinet-assets.mjs

import { chromium } from "playwright";
import { mkdirSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { cabinetHtml, hallBackgroundHtml, variantGeometry } from "./cabinetTemplate.mjs";
import { SLOT_CATALOG } from "../../src/casino/games/slots/slotCatalog.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = resolve(__dirname, "../../public/assets/casino/slots");
const CABINETS_DIR = resolve(OUT_DIR, "cabinets");

function findChromium() {
  const candidates = [
    process.env.PLAYWRIGHT_CHROMIUM_PATH,
    resolve(
      process.env.HOME || "",
      "Library/Caches/ms-playwright/chromium-1148/chrome-mac/Chromium.app/Contents/MacOS/Chromium",
    ),
  ].filter(Boolean);
  for (const c of candidates) {
    if (existsSync(c)) return c;
  }
  return undefined; // fall back to Playwright's own resolution
}

async function main() {
  mkdirSync(CABINETS_DIR, { recursive: true });

  const executablePath = findChromium();
  const browser = await chromium.launch(executablePath ? { executablePath } : {});
  const page = await browser.newPage();

  const geometry = {};
  const aspect = {};

  for (const def of SLOT_CATALOG) {
    const g = variantGeometry(def.cabinetVariant);
    aspect[def.cabinetVariant] = { w: g.w, h: g.h };
    await page.setViewportSize({ width: g.w, height: g.h });
    const html = cabinetHtml({
      variant: def.cabinetVariant,
      accent: def.accent,
      accent2: def.accent2,
      title: def.title,
      jackpot: def.jackpot,
      symbols: def.symbols,
    });
    await page.setContent(html, { waitUntil: "load" });
    await page.waitForTimeout(30);

    const rect = await page.$eval("[data-bake-screen]", (el) => {
      const r = el.getBoundingClientRect();
      return { x: r.x, y: r.y, w: r.width, h: r.height };
    });
    // inset a few px so the DOM screen overlay sits inside the baked bezel, not over it
    const inset = 15;
    const screenRectPct = {
      leftPct: ((rect.x + inset) / g.w) * 100,
      topPct: ((rect.y + inset) / g.h) * 100,
      widthPct: ((rect.w - inset * 2) / g.w) * 100,
      heightPct: ((rect.h - inset * 2) / g.h) * 100,
    };
    geometry[def.cabinetVariant] = screenRectPct;

    const outPath = resolve(CABINETS_DIR, `${def.id}.png`);
    await page.screenshot({ path: outPath, omitBackground: true });
    console.log(`baked ${def.id} (${def.cabinetVariant}) -> ${outPath}`);
  }

  // Hall background — opaque, wide enough to cover the 1920x1080 target with headroom.
  const hallW = 2560;
  const hallH = 1440;
  await page.setViewportSize({ width: hallW, height: hallH });
  await page.setContent(hallBackgroundHtml({ w: hallW, h: hallH }), { waitUntil: "load" });
  await page.waitForTimeout(30);
  const hallPath = resolve(OUT_DIR, "hall-bg.png");
  await page.screenshot({ path: hallPath });
  console.log(`baked hall background -> ${hallPath}`);

  await browser.close();

  const geometryPath = resolve(__dirname, "../../src/casino/games/slots/cabinetGeometry.generated.ts");
  const body = `// AUTO-GENERATED by scripts/casino-slots/generate-cabinet-assets.mjs — do not hand-edit.
// Percentage-based screen overlay rect per cabinet variant, measured from the
// baked cabinet PNG's own [data-bake-screen] element at bake time, plus each
// variant's baked canvas aspect ratio (so the <img> box matches the PNG's
// native ratio exactly and the screen-rect percentages stay accurate).
export const CABINET_SCREEN_RECT: Record<"curved" | "square" | "slim", { leftPct: number; topPct: number; widthPct: number; heightPct: number }> = ${JSON.stringify(geometry, null, 2)};

export const CABINET_ASPECT: Record<"curved" | "square" | "slim", { w: number; h: number }> = ${JSON.stringify(aspect, null, 2)};
`;
  writeFileSync(geometryPath, body);
  console.log(`wrote geometry -> ${geometryPath}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
